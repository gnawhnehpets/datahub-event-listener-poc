"""Create the proposed domain when a Propose New Domain request is approved.

A stripped version of the full handler: the derivation is kept verbatim, the
machinery around it is gone. No Plan object, no Mutation dataclass, no handler
registry, no base class -- this runs three GraphQL calls in order and returns
the URN.

WHAT IS NOT STRIPPED, AND MUST NOT BE

The derivation below looks like ceremony and is not. Each step exists because
its absence produced a wrong governance artifact:

* Deriving Level 1 upward from the chosen parent, rather than asking for both.
  The form cannot filter a Level 2 list by a Level 1 selection, so asking for
  both invited mismatched pairs that were only caught after all three approvals.

* ``select_code`` refusing to guess when a Level 1 carries several GC codes.
  Guessing stamps a wrong-but-valid code onto the domain and nobody finds out.

* The depth check. A domain at MAX_DEPTH cannot take a child, and the taxonomy
  is the thing the whole workflow exists to protect.

* Deriving the id from the *code* rather than the name, so two domains named
  the same under different parents do not collide on one URN.

Rewrite this file freely; keep those four properties.
"""

from __future__ import annotations

import logging

from actions import properties
from actions.client import DataHubClient
from actions.domain_code import build_domain_code, select_code
from actions.errors import DataHubError
from actions.fields import FormFields, slugify
from actions.hierarchy import (
    DomainNode,
    HierarchyError,
    domain_node_from_entity,
    level_for,
    validate_hierarchy,
)

logger = logging.getLogger(__name__)

# Generated by workflows/definitions/generate_form_fields.py -- one dropdown per
# parent domain, so the id is not fixed and has to be discovered by prefix.
LEVEL_2_PREFIX = "level_2_"

OWNER_FIELDS: dict[str, str] = {
    "technical_owners": "urn:li:ownershipType:__system__technical_owner",
    "business_owners": "urn:li:ownershipType:__system__business_owner",
    "data_stewards": "urn:li:ownershipType:__system__data_steward",
}

CREATE_DOMAIN = """
mutation createDomain($input: CreateDomainInput!) {
  createDomain(input: $input)
}
"""


def create_domain(client: DataHubClient, fields: FormFields, source_urn: str) -> str:
    """Create and enrich the domain. Returns its URN.

    Idempotent by construction: the URN is deterministic, the create is skipped
    if the entity already exists, and both enrich calls are upserts. A framework
    retry therefore converges rather than duplicating.
    """
    name = fields.require("new_domain_name")
    description = fields.one("new_domain_description")

    parent = _load_parent(client, fields.one("parent_domain"), "Parent")
    parent = _narrow_to_level_2(client, fields, parent)
    level = level_for(parent)

    if parent is None:
        level_1 = level_2 = None
    elif not parent.ancestors:
        # The chosen parent is itself a root, so the new domain is Level 2.
        level_1, level_2 = parent, None
    else:
        # The chosen parent is Level 2, so the new domain is Level 3 and the
        # Level 1 is the parent's immediate ancestor. level_for() has already
        # rejected anything deeper.
        level_1 = _load_parent(client, parent.ancestors[0], "Derived Level 1")
        level_2 = parent

    # Re-check the derived pair against the same invariants a hand-entered pair
    # had to satisfy. This should never fire; it is here so a change to the
    # derivation cannot silently produce an invalid lineage.
    validate_hierarchy(level_1, level_2)

    level_1_code = (
        select_code(level_1.name, level_1.codes, fields.one("l1_gc_domain_code"))
        if level_1
        else None
    )
    level_2_code = select_code(level_2.name, level_2.codes, None) if level_2 else None
    code = build_domain_code(name, level_1_code, level_2_code)

    entity_id = slugify(code)
    entity_urn = f"urn:li:domain:{entity_id}"
    logger.info(
        "Request %s -> domain code %s, level %s, urn %s", source_urn, code, level, entity_urn
    )

    # ---- create -----------------------------------------------------------
    if client.entity_exists(entity_urn):
        # Treating "exists" as a reason to abort would leave a partially
        # configured domain stuck forever, so skip the create and keep going.
        logger.info("%s already exists; skipping create and continuing", entity_urn)
    else:
        create_input: dict[str, object] = {"id": entity_id, "name": name}
        if description:
            create_input["description"] = description
        if parent is not None:
            create_input["parentDomain"] = parent.urn

        returned = client.execute(CREATE_DOMAIN, {"input": create_input}).get("createDomain")
        if returned and returned != entity_urn:
            raise DataHubError(
                f"Deterministic URN assumption broken: predicted {entity_urn} "
                f"but createDomain returned {returned}"
            )
        logger.info("Created %s from %s", entity_urn, source_urn)

    # ---- enrich -----------------------------------------------------------
    # Failures propagate. Both calls are idempotent upserts against a
    # deterministic URN, so re-running the whole thing converges -- which is
    # exactly what a framework retry does.
    owners = _owner_inputs(fields)
    if owners:
        logger.info("Adding %d owner(s) to %s", len(owners), entity_urn)
        client.execute(
            properties.ADD_OWNERS,
            {"input": {"resourceUrn": entity_urn, "owners": owners}},
        )

    params = properties.structured_property_values(
        [(properties.GC_DOMAIN_CODE, code), (properties.LOB_LEVEL, f"Level {level}")]
    )
    if params:
        logger.info("Setting gcDomainCode=%s, lobLevel=Level %s on %s", code, level, entity_urn)
        client.execute(
            properties.UPSERT_PROPERTIES,
            {"input": {"assetUrn": entity_urn, "structuredPropertyInputParams": params}},
        )

    return entity_urn


def _narrow_to_level_2(
    client: DataHubClient, fields: FormFields, parent: DomainNode | None
) -> DomainNode | None:
    """Apply the Level 2 dropdown, if the requester used it.

    ``parent_domain`` names the Level 1; a ``level_2_<slug>`` field narrows it
    to one of that domain's children. Resolution is by display name because
    ``allowedValues`` cannot be used on a URN field, and is scoped to the
    selected parent -- so a name only has to be unique among siblings.
    """
    if parent is None:
        return None  # nothing to narrow; a root-level proposal

    chosen = next(
        (
            value
            for field_id in fields.ids()
            if field_id.startswith(LEVEL_2_PREFIX)
            for value in [fields.one(field_id)]
            if value and value.strip()
        ),
        None,
    )
    if chosen is None:
        return parent

    chosen = chosen.strip()
    children = [domain_node_from_entity(e) for e in client.get_child_domains(parent.urn)]
    matches = [child for child in children if child.name == chosen]

    if not matches:
        available = ", ".join(sorted(c.name for c in children)) or "none"
        raise HierarchyError(
            f"{chosen!r} is not a child of {parent.name!r} (children: {available}). "
            f"The Level 2 dropdown is generated from the domain tree and may be "
            f"stale; re-run generate_form_fields.py and re-submit."
        )
    if len(matches) > 1:
        raise HierarchyError(
            f"{parent.name!r} has {len(matches)} children named {chosen!r}, so the "
            f"selection is ambiguous. Rename one of them."
        )
    return _load_parent(client, matches[0].urn, "Level 2")


def _load_parent(client: DataHubClient, urn: str | None, label: str) -> DomainNode | None:
    if not urn:
        return None
    entity = client.get_domain(urn)
    if entity is None:
        raise HierarchyError(f"{label} domain {urn} does not exist")
    return domain_node_from_entity(entity)


def _owner_entity_type(urn: str) -> str:
    """CORP_GROUP or CORP_USER, from the urn itself.

    The owner fields accept either -- naming a team rather than a person is the
    normal case for a data steward -- and addOwners rejects the whole call if
    the declared type does not match the urn:

        Expected a corp user urn, found urn:li:corpGroup:...

    That failure lands AFTER the domain has been created, so the domain exists
    with no owners and no structured properties, and every retry hits it again.
    """
    return "CORP_GROUP" if ":corpgroup:" in urn.lower() else "CORP_USER"


def _owner_inputs(fields: FormFields) -> list[dict]:
    owners: list[dict] = []
    for field_id, ownership_type in OWNER_FIELDS.items():
        for urn in fields.all(field_id):
            owners.append(
                {
                    "ownerUrn": urn,
                    "ownerEntityType": _owner_entity_type(urn),
                    "ownershipTypeUrn": ownership_type,
                }
            )
    return owners
